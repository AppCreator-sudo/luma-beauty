import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import {DatabaseSync} from 'node:sqlite';

test('publication galleries, ownership, atomic edits, ordering and private paginated feed',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'atelie-media-')),origin='http://localhost:3198';
  const legacy=new DatabaseSync(path.join(dir,'atelie.sqlite'));
  legacy.exec(`CREATE TABLE users(id TEXT PRIMARY KEY,login TEXT UNIQUE NOT NULL,password TEXT NOT NULL,recovery TEXT NOT NULL,created INTEGER NOT NULL);
    CREATE TABLE works(id TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),image TEXT NOT NULL,caption TEXT NOT NULL,created INTEGER NOT NULL);
    INSERT INTO users VALUES('legacy-user','legacy','disabled','disabled',1);
    INSERT INTO works VALUES('legacy-work','legacy-user','/uploads/legacy.webp','Старая работа',1);`);
  legacy.close();
  const child=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'3198',DATA_DIR:dir,APP_ORIGIN:origin,NODE_ENV:'test'},stdio:['ignore','pipe','pipe']});
  let logs='';child.stdout.on('data',b=>logs+=b);child.stderr.on('data',b=>logs+=b);
  t.after(async()=>{child.kill();await new Promise(r=>child.once('exit',r));fs.rmSync(dir,{recursive:true,force:true})});
  let ready=false;for(let i=0;i<100;i++){try{if((await fetch(origin+'/api/health')).ok){ready=true;break}}catch{}await new Promise(r=>setTimeout(r,100))}assert.ok(ready,logs);
  const client=()=>({cookie:'',async call(url,body,method='GET'){
    const form=body instanceof FormData;
    const r=await fetch(origin+'/api'+url,{method,headers:{Origin:origin,Cookie:this.cookie,...(form?{}:{'Content-Type':'application/json'})},body:body===undefined?undefined:form?body:JSON.stringify(body)});
    if(r.headers.get('set-cookie'))this.cookie=r.headers.get('set-cookie').split(';')[0];
    return {status:r.status,data:await r.json()};
  }});
  const master=client(),other=client(),buyer=client(),guest=client();
  const migrated=new DatabaseSync(path.join(dir,'atelie.sqlite'));
  assert.equal(migrated.prepare('SELECT image FROM work_images WHERE work_id=?').get('legacy-work').image,'/uploads/legacy.webp');
  assert.equal(migrated.prepare('SELECT pinned FROM works WHERE id=?').get('legacy-work').pinned,0);
  migrated.close();
  for(const [c,login,role] of [[master,'author','master'],[other,'another','master'],[buyer,'reader','client']])assert.equal((await c.call('/auth/register',{login,password:'MediaTestPassword123',account_type:role},'POST')).status,201);
  const profile={name:'Тест портфолио',slug:'media-master',city:'Москва',published:true};
  const mid=(await master.call('/profile',profile,'PUT')).data.user_id;
  await other.call('/profile',{...profile,slug:'other-master'},'PUT');
  const service=(await master.call('/services',{name:'Услуга',price:1200,duration:60},'POST')).data.id;
  const foreignService=(await other.call('/services',{name:'Чужая услуга',price:800,duration:30},'POST')).data.id;
  const image=await sharp({create:{width:45,height:60,channels:3,background:'#65182d'}}).png().toBuffer();
  const form=(count=1,fields={})=>{
    const body=new FormData();body.set('caption','Серия фотографий');body.set('service_id',service);
    for(const [k,v] of Object.entries(fields))body.set(k,typeof v==='string'?v:JSON.stringify(v));
    for(let i=0;i<count;i++)body.append('image',new Blob([image],{type:'image/png'}),'photo'+i+'.png');
    return body;
  };
  const created=await master.call('/works',form(3),'POST');assert.equal(created.status,201);
  assert.equal((await master.call('/works',form(1,{caption:'   '}),'POST')).status,400);
  assert.equal((await master.call('/works',form(1,{service_id:''}),'POST')).status,400);
  assert.equal((await master.call('/services/'+service,undefined,'DELETE')).status,409);
  const id=created.data.id,detail=(await guest.call('/works/'+id)).data;
  assert.equal(detail.images.length,3);assert.equal(detail.image,detail.images[0].image);
  const inspiration=await guest.call('/inspiration');assert.equal(inspiration.status,200);assert.equal(inspiration.data.items[0].id,id);
  assert.equal((await buyer.call('/feed')).data.items.length,0);
  assert.equal((await guest.call('/feed')).status,401);
  await buyer.call('/masters/'+mid+'/follow',{},'POST');
  let feed=(await buyer.call('/feed')).data;assert.equal(feed.items[0].id,id);assert.equal(feed.items[0].images.length,3);
  await buyer.call('/works/'+id+'/save',{},'POST');assert.equal((await buyer.call('/feed')).data.items[0].saved,1);
  assert.equal((await buyer.call('/inspiration')).data.items[0].saved,1);
  assert.equal((await other.call('/works/'+id,{pinned:true},'PATCH')).status,404);
  assert.equal((await buyer.call('/works/'+id,{pinned:true},'PATCH')).status,403);
  assert.equal((await other.call('/works/'+id,form(0,{existing_images:[]}), 'PUT')).status,404);
  assert.equal((await master.call('/works/'+id,form(0,{existing_images:[]}), 'PUT')).status,400);
  assert.equal((await master.call('/works/'+id,form(0,{existing_images:['foreign-photo']}),'PUT')).status,400);
  assert.equal((await master.call('/works/'+id,form(0,{existing_images:detail.images.map(p=>p.id),service_id:foreignService}),'PUT')).status,400);
  assert.equal((await master.call('/works',form(7),'POST')).status,400);
  const fileCount=()=>fs.readdirSync(path.join(dir,'uploads')).length;
  const beforeFiles=fileCount(),bad=form(1);bad.append('image',new Blob(['not an image']),'invalid.png');
  assert.equal((await master.call('/works',bad,'POST')).status,400);assert.equal(fileCount(),beforeFiles);
  const retained=[detail.images[2].id,detail.images[0].id];
  const edit=await master.call('/works/'+id,form(1,{existing_images:retained,photo_order:[{upload:0},{id:retained[0]},{id:retained[1]}],caption:'Новая обложка'}),'PUT');
  assert.equal(edit.status,200);
  const updated=(await guest.call('/works/'+id)).data;assert.equal(updated.caption,'Новая обложка');assert.equal(updated.images.length,3);assert.equal(updated.images[1].id,retained[0]);assert.equal(updated.image,updated.images[0].image);assert.notEqual(updated.image,detail.image);
  assert.equal((await fetch(origin+detail.images[1].image)).status,404);
  assert.equal((await buyer.call('/feed')).data.items[0].saved,1);
  assert.equal((await master.call('/works/'+id,{pinned:true},'PATCH')).status,200);
  const ids=[id];for(let i=0;i<13;i++){const r=await master.call('/works',form(),'POST');assert.equal(r.status,201);ids.push(r.data.id)}
  assert.equal((await master.call('/works/'+ids[1],{pinned:true},'PATCH')).status,200);
  assert.equal((await master.call('/works/'+ids[2],{pinned:true},'PATCH')).status,200);
  assert.equal((await master.call('/works/'+ids[3],{pinned:true},'PATCH')).status,400);
  assert.equal((await master.call('/works/order',{ids:[id,id]},'PUT')).status,400);
  assert.equal((await master.call('/works/order',{ids},'PUT')).status,200);
  const portfolio=(await guest.call('/profiles/media-master')).data.works;assert.equal(portfolio[0].id,id);assert.equal(portfolio[3].id,ids[3]);
  // Equal timestamps exercise the cursor tie-breaker, independent of timing on CI.
  const db=new DatabaseSync(path.join(dir,'atelie.sqlite'));db.prepare('UPDATE works SET created=?').run(Date.now());db.close();
  feed=(await buyer.call('/feed')).data;assert.equal(feed.items.length,12);assert.ok(feed.next);
  const second=(await buyer.call('/feed?cursor='+encodeURIComponent(feed.next))).data;
  assert.equal(second.items.length,2);assert.equal(second.next,null);assert.equal(new Set([...feed.items,...second.items].map(w=>w.id)).size,14);
  assert.equal((await buyer.call('/feed?cursor=invalid')).status,400);
  const firstInspiration=(await guest.call('/inspiration')).data;assert.equal(firstInspiration.items.length,12);assert.ok(firstInspiration.next);
  const secondInspiration=(await guest.call('/inspiration?cursor='+encodeURIComponent(firstInspiration.next))).data;
  assert.equal(secondInspiration.items.length,2);assert.equal(secondInspiration.next,null);
  assert.deepEqual(new Set([...firstInspiration.items,...secondInspiration.items].map(w=>w.id)),new Set(ids),'Equal-timestamp inspiration pages contain each public work exactly once');
  assert.equal((await guest.call('/inspiration?cursor=invalid')).status,400);
  await master.call('/profile',{...profile,published:false},'PUT');
  assert.equal((await buyer.call('/feed')).data.items.length,0);assert.equal((await buyer.call('/works/'+id)).status,404);
  assert.equal((await guest.call('/inspiration')).data.items.length,0,'Unpublished solo works remain private');
  assert.equal((await buyer.call('/library')).data.works.length,0,'Unpublished solo works disappear from saved public works');
  assert.equal((await master.call('/works/'+id)).status,200);
  await master.call('/profile',profile,'PUT');await buyer.call('/masters/'+mid+'/follow',undefined,'DELETE');
  assert.equal((await buyer.call('/feed')).data.items.length,0);
  const photoUrls=updated.images.map(p=>p.image);
  assert.equal((await master.call('/works/'+id,undefined,'DELETE')).status,200);
  for(const url of photoUrls)assert.equal((await fetch(origin+url)).status,404);
  assert.equal((await buyer.call('/library')).data.works.length,0);
});
