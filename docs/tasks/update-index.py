"""Rebuild the task-list Markdown from registry.json; does not modify app code."""
from pathlib import Path
import json

BASE = Path(__file__).resolve().parent
registry = json.loads((BASE / 'registry.json').read_text(encoding='utf-8'))
labels = {'ready':'Готова к анализу', 'blocked':'Зависимости / согласование',
          'awaiting_input':'Внешнее условие', 'deferred':'Отложена / решение',
          'published':'Опубликовано', 'approved':'Согласовано', 'verified':'Проверено в указанном объёме',
          'in_progress':'В работе', 'local_done':'Сделано локально', 'awaiting_approval':'Ожидает одобрения'}
rows = sorted(registry['tasks'], key=lambda item:item['order'])
by_id = {item['id']:item for item in rows}
next_task = by_id[registry['next_task_id']]
lines = ['# Luma Beauty — отдельные задачи', '',
         'Единый список задач. Каждая строка ведёт к самостоятельной карточке: граница, зависимости, навыки, реальные файлы, порядок, приёмка и фактические даты. '
         'Обновлено '+registry['updated_at']+'; все даты Asia/Novosibirsk.', '',
         '**Точка продолжения:** ['+next_task['id']+' — '+next_task['title']+']('+next_task['card']+'). '
         'Действие и условия начала указаны в выбранной карточке; статус ready не заменяет нужное одобрение.', '',
         '[Как работать новому чату](../NEW_CHAT_GUIDE.md) · [Checkpoint](../WORK_CHECKPOINT.md) · '
         '[Текущая версия](../CURRENT_STATE.md) · [Эталоны и реализованные экраны](../V2_UI_REFERENCE_IMPLEMENTATION.md) · [Этапы](../PROJECT_ROADMAP.md)', '',
         '## Как выбирать', '',
         '1. При явном «продолжай» открыть checkpoint и первую доступную карточку. При конкретном ID открыть её и зависимости.',
         '2. Не брать `deferred` в реализацию; `awaiting_input` требует указанного домена/устройства/решения. `blocked` не означает, что функция сломана.',
         '3. Прочитать указанные навыки и код. Если эталона/функции нет или есть конфликт, сначала показать конкретное решение пользователю.',
         '4. Отметить чат-исполнитель и статус «В работе» перед изменениями; не дублировать занятую задачу. Не выполнять всю очередь автоматически.',
         '5. Новая карточка BUG-002 и далее для нового дефекта; не открывать снова BUG-001 без воспроизведения.', '',
         '## Перенос UI — оставшаяся очередь', '',
         'Порядок: **U-09 → U-10 → U-11**. Остатки уточнены в [матрице U-10-01](../V2_REMAINING_UI_AUDIT.md): выполненное повторно не переделывать; проверки и дефекты имеют отдельные карточки.', '',
         '| ID / карточка | Статус | Зависимости |', '| --- | --- | --- |']
def emit(items, dates=False):
    for item in items:
        dep = ', '.join('['+x+']('+by_id[x]['card']+')' for x in item['dependencies']) or '—'
        value = item['published_at'] or item['verified_at'] or item['approved_at'] or 'В источниках; отдельно не зафиксировано'
        lines.append('| ['+item['id']+' — '+item['title']+']('+item['card']+') | '+labels[item['status']]+' | '+(value if dates else dep)+' |')
emit([x for x in rows if x['phase']=='ui'])
lines += ['', '## Подготовка репозитория и облачной разработки', '',
          'Прямое поручение 14.10.2026; не заменяет очередь UI и не разрешает production-выпуск.', '',
          '| ID / карточка | Статус | Зависимости |', '| --- | --- | --- |']
emit([x for x in rows if x['phase']=='operations'])
lines += ['', '## Функции после UI', '',
          'Группы F-01…F-07 сохранены из прежнего плана, широкие этапы разделены на действия. '
          'F-08…F-12 выделяют ранее открытые проверки/вопросы, а не новые одобренные функции. '
          'Начало функционального этапа не разрешает автоматическую миграцию, удаление аккаунта или покупку домена.', '',
          '| ID / карточка | Статус | Зависимости |', '| --- | --- | --- |']
emit([x for x in rows if x['phase'] in ('functional','verification','decision')])
lines += ['', '## Выполнено или согласовано в указанном объёме', '',
          'Эти карточки — источники решений/доказательств; при «продолжай» повторно не выполнять. '
          'Дата выпуска не является датой начала и не доказывает проверку будущих изменений.', '',
          '| ID / карточка | Статус | Фактическая публикация / проверка / согласование |', '| --- | --- | --- |']
emit([x for x in rows if x['phase']=='completed'],True)
lines += ['', '## Ведение реестра', '',
          '- `ready` — можно начать указанное в карточке действие; согласование реализации при этом не подразумевается.',
          '- `awaiting_approval` — конкретный макет/решение показан, ответа ещё нет; зависимую работу не начинать.',
          '- `in_progress` → `local_done` → `verified` → `published` различают работу, локальный результат, проверку и выпуск. '
          'Для чистого анализа достаточен согласованный результат `approved`, для документации — `verified`; публикация не применяется.',
          '- `approved`, `verified`, `published` закрывают только написанную границу; родительский U-10/F-03 нельзя закрывать по одной дочерней карточке.',
          '- `registry.json` содержит ID/порядок/статусы/зависимости/фактические даты/чат. Карточка содержит подробный контракт, решения пользователя и отчёт. '
          'Изменять оба при переходе статуса, неизвестные даты оставлять `null`; будущие сроки не придумывать.',
          '- После изменения выполнить из корня: `python -X utf8 docs/tasks/update-index.py`. Это обновляет только данный список.',
          '- Обновить checkpoint/state/roadmap; UI-решение внести в UI-журнал. Release-отчёт нужен только при действительном выпуске. '
          'PNG и старые RELEASE не перезаписывать. Секретов/личных данных в карточках нет.', '',
          '[Машиночитаемый реестр](registry.json) · [История прежних документов](../archive/README.md)', '',
          'Будущие даты всех незавершённых реализаций **не назначены**. '
          'Документация помогает продолжить проект, но не гарантирует автоматическое чтение истории чужих чатов.']
(BASE/'README.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Updated task index:',len(rows),'cards; next',next_task['id'])
