import fs from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import multer from 'multer';
import sharp from 'sharp';

const RULES=JSON.parse(await fs.readFile(new URL('./image-rules.json',import.meta.url),'utf8'));
const FORMATS=new Map([['image/jpeg','jpeg'],['image/png','png'],['image/webp','webp']]);
const OWNED=/^\/uploads\/atelie-media-(?:logo|cover|portrait)-[a-f0-9-]{36}\.webp$/;

function signature(buffer){
  if(buffer.length>=3&&buffer[0]===0xff&&buffer[1]===0xd8&&buffer[2]===0xff)return 'jpeg';
  if(buffer.length>=8&&buffer.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])))return 'png';
  if(buffer.length>=12&&buffer.toString('ascii',0,4)==='RIFF'&&buffer.toString('ascii',8,12)==='WEBP')return 'webp';
  return null;
}

// Only files generated by this helper can be removed. Existing photos remain
// untouched, and the caller removes the previous photo after a successful save.
export function createImageUpload({dataDir,fail,fields=0}){
  const directory=path.resolve(dataDir,'uploads');
  const upload=multer({storage:multer.memoryStorage(),limits:{fileSize:RULES.maxBytes,files:1,fields,parts:fields+1,fieldSize:16384}}).single('image');
  function middleware(req,res,next){upload(req,res,error=>{
    if(error)return res.status(error.code==='LIMIT_FILE_SIZE'?413:400).json({error:error.code==='LIMIT_FILE_SIZE'?'Фотография должна быть меньше 8 МБ':'Выберите одну фотографию JPG, PNG или WebP'});
    next();
  })}
  async function save(file,kind){
    if(!['logo','cover','portrait'].includes(kind))throw new Error('Unknown image kind');
    if(!file)fail('Выберите фотографию');
    if(file.buffer.length>RULES.maxBytes)fail('Фотография должна быть меньше 8 МБ');
    const format=signature(file.buffer);
    if(!format||FORMATS.get(file.mimetype)!==format)fail('Выберите фотографию JPG, PNG или WebP');
    const name='atelie-media-'+kind+'-'+randomUUID()+'.webp',temporary=path.join(directory,'.'+name),target=path.join(directory,name);
    const dimensions=kind==='logo'?{width:600,height:600}:kind==='cover'?{width:1600,height:1200}:{width:900,height:1200};
    try{
      const image=sharp(file.buffer,{limitInputPixels:RULES.maxPixels,animated:false});
      const metadata=await image.metadata();
      if(metadata.format!==format||metadata.pages>1)fail('Выберите обычную фотографию JPG, PNG или WebP');
      const rotated=metadata.orientation>=5&&metadata.orientation<=8;
      const width=rotated?metadata.height:metadata.width,height=rotated?metadata.width:metadata.height;
      if(!Number.isSafeInteger(width)||!Number.isSafeInteger(height)||width<=0||height<=0)fail('Не удалось определить размер фото');
      if(width>RULES.maxSide||height>RULES.maxSide||width*height>RULES.maxPixels)fail('Фото должно быть не больше 40 мегапикселей и 10 000 пикселей по каждой стороне');
      const rule=kind==='cover'?RULES.cover:RULES.avatar;
      if(width<rule.minWidth||height<rule.minHeight)fail(kind==='cover'?'Для обложки выберите горизонтальное фото не меньше 800 × 450 пикселей':'Для аватара выберите фото не меньше 256 × 256 пикселей');
      if(kind==='cover'&&rule.landscape&&width<=height)fail('Для обложки выберите горизонтальное фото не меньше 800 × 450 пикселей');
      await fs.mkdir(directory,{recursive:true});
      await image.rotate().resize({...dimensions,fit:'inside',withoutEnlargement:true}).webp({quality:85}).toFile(temporary);
      await fs.rename(temporary,target);
      return '/uploads/'+name;
    }catch(error){
      await fs.rm(temporary,{force:true}).catch(()=>{});
      await fs.rm(target,{force:true}).catch(()=>{});
      if(error.status)throw error;
      if(/pixel limit/i.test(error.message||''))fail('Фото должно быть не больше 40 мегапикселей и 10 000 пикселей по каждой стороне');
      fail('Не удалось прочитать фото. Выберите другое изображение JPG, PNG или WebP');
    }
  }
  async function removeOwned(image){
    if(typeof image!=='string'||!OWNED.test(image))return;
    const target=path.resolve(directory,path.basename(image));
    if(path.dirname(target)!==directory)return;
    await fs.rm(target,{force:true}).catch(()=>{});
  }
  return {middleware,save,removeOwned};
}
